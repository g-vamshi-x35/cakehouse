// Syncs website content into the app bundle. Run after changing the website:
//   npm run sync-images
//
// 1. Copies the website's photos (../public/images/<folders>) into
//    assets/site-images and generates src/lib/image-map.ts, which maps a
//    website path such as "/images/products/cakes/vanilla-cake/2.jpg" to a
//    bundled require(). Photo URLs in the database are website paths, so
//    bundling them makes the app load them instantly and offline.
// 2. Copies the website's short videos + poster frames into assets/site-video
//    and generates src/lib/video-map.ts.
// 3. Generates src/lib/site-data.ts from the website's own data files:
//    product browse tags (src/data/products.ts) and the Premium Cakes photo
//    list (src/data/premium.ts), so the app's sections match the website.
import { copyFileSync, cpSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = join(import.meta.dirname, '..', '..');
const SRC = join(ROOT, 'public', 'images');
const DEST = join(import.meta.dirname, '..', 'assets', 'site-images');
const LIB = join(import.meta.dirname, '..', 'src', 'lib');
const FOLDERS = ['products', 'menu', 'gallery', 'hero', 'brand', 'premium', 'stylish'];
const VIDEOS = ['hero-berry-cake', 'craft-cake-slice', 'promo-pizza', 'custom-decorating'];

// --- photos ---------------------------------------------------------------
rmSync(DEST, { recursive: true, force: true });
const files = [];
for (const folder of FOLDERS) {
  cpSync(join(SRC, folder), join(DEST, folder), { recursive: true });
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.(jpe?g|png|webp)$/i.test(name)) files.push(relative(DEST, full).split(sep).join('/'));
    }
  };
  walk(join(DEST, folder));
}
files.sort();
writeFileSync(
  join(LIB, 'image-map.ts'),
  `// Generated by scripts/sync-images.mjs — do not edit by hand.\n` +
    `export const SITE_IMAGES: Record<string, number> = {\n` +
    files.map((f) => `  "/images/${f}": require("../../assets/site-images/${f}"),`).join('\n') +
    `\n};\n`
);

// --- videos ---------------------------------------------------------------
const VDEST = join(import.meta.dirname, '..', 'assets', 'site-video');
rmSync(VDEST, { recursive: true, force: true });
mkdirSync(VDEST, { recursive: true });
const vlines = [];
for (const v of VIDEOS) {
  copyFileSync(join(ROOT, 'public', 'video', `${v}.mp4`), join(VDEST, `${v}.mp4`));
  let poster = 'null';
  try {
    copyFileSync(join(ROOT, 'public', 'video', `${v}.jpg`), join(VDEST, `${v}.jpg`));
    poster = `require("../../assets/site-video/${v}.jpg")`;
  } catch {
    // no poster frame for this video
  }
  vlines.push(`  "${v}": { video: require("../../assets/site-video/${v}.mp4"), poster: ${poster} },`);
}
writeFileSync(
  join(LIB, 'video-map.ts'),
  `// Generated by scripts/sync-images.mjs — do not edit by hand.\n` +
    `export const SITE_VIDEOS: Record<string, { video: number; poster: number | null }> = {\n${vlines.join('\n')}\n};\n`
);

// --- website data (tags + premium list) -----------------------------------
const site = await import(join(ROOT, 'src', 'data', 'products.ts'));
const premium = await import(join(ROOT, 'src', 'data', 'premium.ts'));
const tags = Object.fromEntries(site.products.filter((p) => p.tags?.length).map((p) => [p.slug, p.tags]));
writeFileSync(
  join(LIB, 'site-data.ts'),
  `// Generated by scripts/sync-images.mjs from the website's src/data — do not edit by hand.\n` +
    `export const BROWSE_TAGS: Record<string, string> = ${JSON.stringify(site.BROWSE_TAGS, null, 2)};\n\n` +
    `/** Product slug -> browse tags (same as the website's menu filters). */\n` +
    `export const PRODUCT_TAGS: Record<string, string[]> = ${JSON.stringify(tags, null, 2)};\n\n` +
    `/** Premium Cakes photo list — shown with "Price on request" if the database is unreachable. */\n` +
    `export const PREMIUM_FALLBACK: { slug: string; name: string; images: string[] }[] = ${JSON.stringify(premium.PREMIUM_CAKES, null, 2)};\n`
);

console.log(`Synced ${files.length} images, ${VIDEOS.length} videos, ${Object.keys(tags).length} tagged products, ${premium.PREMIUM_CAKES.length} premium cakes.`);
