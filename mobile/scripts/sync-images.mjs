// Copies the website's photos (../public/images) into the app bundle and
// generates src/lib/image-map.ts, which maps a website path such as
// "/images/products/cakes/vanilla-cake/2.jpg" to a bundled require().
// Product photo URLs in the database are website paths, which a phone can't
// load until the site is online — bundling them makes the app work offline
// from the website. Re-run after adding photos:  node scripts/sync-images.mjs
import { cpSync, mkdirSync, readdirSync, statSync, writeFileSync, rmSync } from "node:fs";
import { join, relative, sep } from "node:path";

const SRC = join(import.meta.dirname, "..", "..", "public", "images");
const DEST = join(import.meta.dirname, "..", "assets", "site-images");
const FOLDERS = ["products", "menu", "gallery", "hero", "brand"];

rmSync(DEST, { recursive: true, force: true });
const files = [];
for (const folder of FOLDERS) {
  cpSync(join(SRC, folder), join(DEST, folder), { recursive: true });
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.(jpe?g|png|webp)$/i.test(name)) files.push(relative(DEST, full).split(sep).join("/"));
    }
  };
  walk(join(DEST, folder));
}
files.sort();

const lines = files.map((f) => `  "/images/${f}": require("../../assets/site-images/${f}"),`);
writeFileSync(
  join(import.meta.dirname, "..", "src", "lib", "image-map.ts"),
  `// Generated by scripts/sync-images.mjs — do not edit by hand.\n` +
    `export const SITE_IMAGES: Record<string, number> = {\n${lines.join("\n")}\n};\n`
);
console.log(`Synced ${files.length} images.`);
